# list
student = ["Amit", 20, 98.4, "Gwalior", "Amity"]
print(student)

# Type of list
print(type(student))

# len of list
print(len(student))

# Indexing of list
print(student[0])
print(student[4])
print(student[2])

# list slicing
print(student[1:4])
print(student[0:len(student)])

# Access all the values in list
for item in student:
    print(item)